import { cifra, dinero, fechaCorta, fechaHora, legible, nombreCompleto } from '../util/formato'

const texto = (campo, etiqueta, extra = {}) => ({ campo, etiqueta, tipo: 'texto', ...extra })
const numero = (campo, etiqueta, extra = {}) => ({ campo, etiqueta, tipo: 'numero', ...extra })
const decimal = (campo, etiqueta, extra = {}) => ({ campo, etiqueta, tipo: 'decimal', ...extra })
const fecha = (campo, etiqueta, extra = {}) => ({ campo, etiqueta, tipo: 'fecha', ...extra })
const momento = (campo, etiqueta, extra = {}) => ({ campo, etiqueta, tipo: 'fechaHora', ...extra })
const booleano = (campo, etiqueta, extra = {}) => ({ campo, etiqueta, tipo: 'booleano', ...extra })
const opciones = (campo, etiqueta, lista, extra = {}) => ({ campo, etiqueta, tipo: 'enum', opciones: lista, ...extra })
const ref = (campo, etiqueta, ruta, idRef, textoRef, extra = {}) => ({ campo, etiqueta, tipo: 'ref', ruta, idRef, textoRef, ...extra })
const refNumero = (campo, etiqueta, idRef, extra = {}) => ({ campo, etiqueta, tipo: 'refNumero', idRef, ...extra })
const col = (titulo, valor) => ({ titulo, valor })

const nombreDe = (objeto) => objeto?.nombre ?? '—'
const persona = (usuario) => nombreCompleto(usuario)
const ciudadTexto = (ciudad) => (ciudad ? `${ciudad.nombre} (${ciudad.departamento?.nombre ?? ''})` : '—')
const terminalTexto = (terminal) => (terminal ? `${terminal.codigo} · ${terminal.nombre}` : '—')
const vehiculoTexto = (vehiculo) => (vehiculo ? `${vehiculo.matricula} · ${vehiculo.modelo}` : '—')
const rutaTexto = (ruta) => (ruta ? `${ruta.codigo} (${ruta.terminalOrigen?.ciudad?.nombre} → ${ruta.terminalDestino?.ciudad?.nombre})` : '—')
const viajeTexto = (viaje) => (viaje ? `${viaje.codigoViaje} · ${fechaHora(viaje.fechaHoraSalida)}` : '—')
const tipoDocTexto = (tipo) => (tipo ? `${tipo.sigla} · ${tipo.nombre}` : '—')

